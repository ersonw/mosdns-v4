package radius

import (
	"bufio"
	"encoding/binary"
	"errors"
	"fmt"
	"net"
	"os"
	"strings"
)

// errPoolExhausted means every usable address in ip_pool is already pinned.
var errPoolExhausted = errors.New("radius: ip pool is exhausted")

// ipPool is the inclusive IPv4 range handed out by AddUser. Allocation starts
// at the top and walks down: ocserv's dynamic pool normally fills from the
// bottom, so the two are less likely to collide while users migrate to fixed
// addresses.
type ipPool struct {
	first  uint32
	last   uint32
	server uint32 // ocserv's own tun address, never handed to a client
}

// parseIPPool accepts "10.8.0.0/24" or an explicit "10.8.0.2-10.8.0.254".
// A CIDR drops the network and broadcast addresses; a range is used exactly
// as written, which is the way to reserve the gateway or a server address.
func parseIPPool(value string) (*ipPool, error) {
	value = strings.TrimSpace(value)
	if value == "" {
		return nil, nil
	}
	if strings.Contains(value, "/") {
		_, network, err := net.ParseCIDR(value)
		if err != nil {
			return nil, fmt.Errorf("radius: invalid ip_pool %q: %w", value, err)
		}
		ones, bits := network.Mask.Size()
		if bits != 32 {
			return nil, fmt.Errorf("radius: ip_pool %q is not ipv4", value)
		}
		pool, err := poolFromNetwork(network.IP.To4(), ones, nil)
		if err != nil {
			return nil, fmt.Errorf("radius: ip_pool %q: %w", value, err)
		}
		return pool, nil
	}

	parts := strings.SplitN(value, "-", 2)
	if len(parts) != 2 {
		return nil, fmt.Errorf("radius: ip_pool %q must be a CIDR or start-end range", value)
	}
	first, err := parseIPv4(parts[0])
	if err != nil {
		return nil, fmt.Errorf("radius: ip_pool %q: %w", value, err)
	}
	last, err := parseIPv4(parts[1])
	if err != nil {
		return nil, fmt.Errorf("radius: ip_pool %q: %w", value, err)
	}
	if first > last {
		return nil, fmt.Errorf("radius: ip_pool %q is reversed", value)
	}
	return &ipPool{first: first, last: last}, nil
}

// poolFromNetwork builds the usable host range and marks ocserv's own address.
// "server" may be nil, in which case ocserv's usual network+1 is reserved. The
// caller must ensure server is inside the host range; an address outside it is
// ignored because it cannot collide with a lease anyway.
func poolFromNetwork(base net.IP, ones int, server net.IP) (*ipPool, error) {
	base = base.To4()
	if base == nil {
		return nil, fmt.Errorf("not an ipv4 network")
	}
	if ones >= 31 {
		return nil, fmt.Errorf("no room for a server address and leases")
	}
	start := uint64(binary.BigEndian.Uint32(base))
	size := uint64(1) << (32 - ones)
	first := start + 1
	last := start + size - 2
	if first > last {
		return nil, fmt.Errorf("no usable hosts")
	}
	p := &ipPool{first: uint32(first), last: uint32(last)}
	p.server = p.first // ocserv defaults to the first usable address
	if server != nil && server.To4() != nil {
		v := binary.BigEndian.Uint32(server.To4())
		if v >= p.first && v <= p.last {
			p.server = v
		}
	}
	return p, nil
}

// loadPoolFromOcserv reads ipv4-network (with optional ipv4-netmask) from an
// ocserv.conf. The file is generated by VyOS at boot, so it is read once when
// the plugin starts; a network change needs a mosdns reload/restart.
func loadPoolFromOcserv(path string) (*ipPool, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("radius: open ocserv config %q: %w", path, err)
	}
	defer f.Close()

	var network, netmask, serverIP string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			fields := strings.Fields(line)
			if len(fields) < 2 {
				continue
			}
			key, value = fields[0], strings.Join(fields[1:], " ")
		}
		key = strings.ToLower(strings.TrimSpace(key))
		value = strings.TrimSpace(value)
		if i := strings.Index(value, " #"); i >= 0 {
			value = strings.TrimSpace(value[:i])
		}
		switch key {
		case "ipv4-network":
			network = value
		case "ipv4-netmask":
			netmask = value
		case "server-ip":
			serverIP = value
		}
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("radius: read ocserv config %q: %w", path, err)
	}
	if network == "" {
		return nil, fmt.Errorf("radius: %s has no ipv4-network", path)
	}

	var server net.IP
	if serverIP != "" {
		server = net.ParseIP(serverIP)
		if server == nil || server.To4() == nil {
			return nil, fmt.Errorf("radius: server-ip %q is not an ipv4 address", serverIP)
		}
	}

	if strings.Contains(network, "/") {
		addr, n, err := net.ParseCIDR(network)
		if err != nil {
			return nil, fmt.Errorf("radius: ipv4-network %q: %w", network, err)
		}
		ones, bits := n.Mask.Size()
		if bits != 32 {
			return nil, fmt.Errorf("radius: ipv4-network %q is not ipv4", network)
		}
		// VyOS may write "10.8.0.1/24": the address before the slash is the
		// machine's own tun IP, not the network base. Keep it out of the pool.
		if server == nil && addr.To4() != nil && !addr.To4().Equal(n.IP.To4()) {
			server = addr
		}
		return poolFromNetwork(n.IP.To4(), ones, server)
	}

	ip := net.ParseIP(network)
	if ip == nil || ip.To4() == nil {
		return nil, fmt.Errorf("radius: ipv4-network %q is not an ipv4 address", network)
	}
	mask := net.ParseIP(netmask)
	if mask == nil || mask.To4() == nil {
		return nil, fmt.Errorf("radius: ipv4-netmask %q is not an ipv4 netmask", netmask)
	}
	m := net.IPMask(mask.To4())
	ones, bits := m.Size()
	if bits != 32 {
		return nil, fmt.Errorf("radius: ipv4-netmask %q is not a contiguous ipv4 mask", netmask)
	}
	base := ip.To4().Mask(m)
	if server == nil && !ip.To4().Equal(base) {
		server = ip
	}
	return poolFromNetwork(base, ones, server)
}

func parseIPv4(value string) (uint32, error) {
	ip := net.ParseIP(strings.TrimSpace(value))
	if ip == nil || ip.To4() == nil {
		return 0, fmt.Errorf("%q is not an ipv4 address", value)
	}
	return binary.BigEndian.Uint32(ip.To4()), nil
}

func ipv4String(v uint32) string {
	ip := make(net.IP, 4)
	binary.BigEndian.PutUint32(ip, v)
	return ip.String()
}

func usableTunnelIP(v uint32) bool {
	ip := net.IP(make([]byte, 4))
	binary.BigEndian.PutUint32(ip, v)
	return !ip.IsUnspecified() && !ip.IsLoopback() && !ip.IsMulticast() &&
		!ip.Equal(net.IPv4bcast)
}

// allocate picks the highest unused address in the pool. The caller inserts
// the user immediately afterwards; the unique index on ip catches the rare
// race with a concurrent SetIP, and AddUser retries with a new candidate.
func (s *store) allocate(pool *ipPool) (string, error) {
	if pool == nil {
		return "", nil
	}
	used, err := s.usedIPs()
	if err != nil {
		return "", err
	}
	v := pool.last
	for {
		if usableTunnelIP(v) && v != pool.server && !used[ipv4String(v)] {
			return ipv4String(v), nil
		}
		if v == pool.first {
			break
		}
		v--
	}
	return "", errPoolExhausted
}

func (s *store) usedIPs() (map[string]bool, error) {
	rows, err := s.db.Query("SELECT ip FROM " + userTableName + " WHERE ip <> ''")
	if err != nil {
		return nil, fmt.Errorf("radius: list fixed ips: %w", err)
	}
	defer rows.Close()
	used := make(map[string]bool)
	for rows.Next() {
		var ip string
		if err := rows.Scan(&ip); err != nil {
			return nil, fmt.Errorf("radius: scan fixed ip: %w", err)
		}
		used[ip] = true
	}
	return used, rows.Err()
}
