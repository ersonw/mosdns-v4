#!/usr/bin/env python3
"""Generate /etc/mosdns/rule/tiktok_ip.txt (fakeip_nat capture prefixes).

The TikTok app ships its own address book and connects straight to ByteDance
edges without asking the resolver, so those destinations never reach the fake
range. fakeip_nat carries them instead through capture_file: every prefix in
that file gets a route into the tun device plus a policy rule pinning it to the
main table.

fakeip_nat scans the capture list per packet and installs one ip rule per
entry, so the list must stay short:

* ByteDance (AS396986) is collapsed to its /16 blocks. 71.18/16 alone holds
  most of the ASN, which is why every hand written TikTok edge lives there.
* Akamai (AS20940) is only kept for the /24 edges that were captured failing on
  this line. Pulling whole Akamai /16 blocks would also drag Apple and other
  Akamai customers through the TikTok outlet.

Prefixes whose owner changed hands (99.86 was Amazon, 167.82 was Fastly) are
dropped: they were never TikTok.
"""

import argparse
import ipaddress
import json
import os
import sys
import urllib.request

BYTEDANCE_ASN = "AS396986"
AKAMAI_ASN = "AS20940"

# Akamai edges observed failing on eth1 while the TikTok app connected to them.
OBSERVED_AKAMAI = [
    "23.55.179.0/24",
    "23.214.168.0/24",
    "23.48.5.0/24",
    "96.7.39.0/24",
    "23.218.94.0/24",
]

CN_PREFIX_FILE = "/etc/mosdns/rule/prefix_cn.txt"
DEFAULT_OUT = "/etc/mosdns/rule/tiktok_ip.txt"
API = "https://stat.ripe.net/data/announced-prefixes/data.json?resource="


def fetch_prefixes(asn: str) -> list:
    with urllib.request.urlopen(API + asn, timeout=25) as resp:
        payload = json.load(resp)
    out = []
    for item in payload["data"]["prefixes"]:
        prefix = item["prefix"]
        if ":" in prefix:
            continue
        out.append(ipaddress.ip_network(prefix, strict=False))
    return out


def load_cn_prefixes(path: str) -> list:
    if not os.path.exists(path):
        return []
    nets = []
    with open(path, "r", encoding="utf-8", errors="ignore") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            try:
                nets.append(ipaddress.ip_network(line, strict=False))
            except ValueError:
                continue
    return nets


def overlaps_any(candidate, nets) -> bool:
    for net in nets:
        if net.version == candidate.version and net.overlaps(candidate):
            return True
    return False


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    cn_nets = load_cn_prefixes(CN_PREFIX_FILE)

    bytedance = fetch_prefixes(BYTEDANCE_ASN)
    akamai = fetch_prefixes(AKAMAI_ASN)

    blocks = {}
    for prefix in bytedance:
        block = ipaddress.ip_network(
            ".".join(prefix.exploded.split(".")[:2]) + ".0.0/16", strict=False
        )
        blocks.setdefault(block, []).append(prefix)

    # A /16 that only holds one or two announced prefixes is not worth carrying
    # as a /16: the block may be shared with unrelated neighbours. Emit the
    # exact prefixes there and keep /16 collapse for the dense blocks.
    MIN_MEMBERS_FOR_SLASH16 = 8

    selected = []
    notes = []
    for block, members in sorted(blocks.items(), key=lambda kv: str(kv[0])):
        if overlaps_any(block, cn_nets):
            notes.append(f"# skip {block}: overlaps a CN prefix")
            continue
        if len(members) >= MIN_MEMBERS_FOR_SLASH16:
            selected.append(block)
            notes.append(f"# {block}  ({len(members)} {BYTEDANCE_ASN} prefixes inside)")
            continue
        for member in sorted(members, key=str):
            if overlaps_any(member, cn_nets):
                continue
            if member not in selected:
                selected.append(member)
        notes.append(
            f"# {block}  listed as {len(members)} exact prefix(es), too sparse for /16"
        )

    akamai_candidates = [ipaddress.ip_network(p, strict=False) for p in OBSERVED_AKAMAI]
    for candidate in akamai_candidates:
        if not any(candidate.overlaps(p) for p in akamai):
            notes.append(f"# skip {candidate}: no longer announced by {AKAMAI_ASN}")
            continue
        if overlaps_any(candidate, cn_nets):
            notes.append(f"# skip {candidate}: overlaps a CN prefix")
            continue
        if candidate not in selected:
            selected.append(candidate)
            notes.append(f"# {candidate}  (observed failing {AKAMAI_ASN} edge)")

    header = [
        "# Generated by scripts/gen_tiktok_capture.py - do not hand edit.",
        f"# ByteDance edges: {BYTEDANCE_ASN}, collapsed to /16 blocks.",
        f"# Akamai edges: {AKAMAI_ASN}, only the /24s captured failing on this line.",
        "# fakeip_nat installs one route and one policy rule per line and scans the",
        "# list per packet, so the list stays short on purpose.",
        "#",
    ]
    body = [str(p) for p in selected]
    text = "\n".join(header + notes + body) + "\n"

    if args.dry_run:
        print(text)
        return 0

    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {args.out}: {len(body)} prefixes", file=sys.stderr)
    for note in notes:
        print(note, file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
